// Builds theme.css (the file Obsidian loads) from src/*.css and the bundled font files.
//   node scripts/build.mjs            write theme.css
//   node scripts/build.mjs --check    fail if theme.css is not what the sources build to
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(root, 'manifest.json'), 'utf8'));

const FONTS = [
	{ file: 'JetBrainsMono-400.woff2', weight: 400 },
	{ file: 'JetBrainsMono-700.woff2', weight: 700 },
];

function fontFaces() {
	return FONTS.map(({ file, weight }) => {
		const base64 = readFileSync(join(root, 'fonts', file)).toString('base64');
		return `@font-face {\n\tfont-family: 'JetBrains Mono';\n\tfont-style: normal;\n\tfont-weight: ${weight};\n\tfont-display: swap;\n\tsrc: url(data:font/woff2;base64,${base64}) format('woff2');\n}\n`;
	}).join('\n');
}

export function build() {
	const header = `/*\n * ${manifest.name} ${manifest.version}: a dense, calm, monospace theme for Obsidian.\n * Based on the Slate design system. PolyForm Noncommercial 1.0.0 (see LICENSE); JetBrains Mono is SIL OFL 1.1.\n * https://github.com/CodingJinxx/obsidian-slate-theme\n *\n * Generated by scripts/build.mjs from src/*.css. Edit the sources, not this file.\n */\n\n`;
	const sources = readdirSync(join(root, 'src'))
		.filter((name) => name.endsWith('.css'))
		.sort()
		.map((name) => readFileSync(join(root, 'src', name), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n');
	return header + '/* JetBrains Mono 400 and 700, subset to Latin (see scripts/subset-fonts.py), embedded so the theme works offline. */\n' + fontFaces() + '\n' + sources.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const out = join(root, 'theme.css');
	const css = build();
	if (process.argv.includes('--check')) {
		const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
		if (current !== css) {
			console.error('theme.css is out of date. Run `npm run build` and commit it.');
			process.exit(1);
		}
		console.log('theme.css is up to date.');
	} else {
		writeFileSync(out, css);
		console.log(`theme.css written (${(css.length / 1024).toFixed(0)} KB).`);
	}
}
